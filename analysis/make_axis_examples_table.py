#!/usr/bin/env python3
"""make_axis_examples_table.py — emit paper/latex/tab_axis_examples.tex from verified challenge
data. Selects one en-hi exemplar per difficulty axis by exact source match, recomputes its
diagnostics with analysis/axis_contrast.py, and transliterates the Hindi MT to IAST. Devanagari is
wrapped in \\dev{} (LuaLaTeX + Noto Sans Devanagari). Nothing is hand-typed, so no transcription
error can creep in, and the axis flags printed here are the same ones the results use."""
from __future__ import annotations

import ast
import sys
from pathlib import Path

import pandas as pd
from indic_transliteration import sanscript

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))
from axis_contrast import AXES, load_challenge  # noqa: E402

OUT = ROOT / "paper/latex/tab_axis_examples.tex"

# (heading, source-match, human gloss of the error, which signal to cite)
CHOSEN = [
 ("no axis", "Raja and Chhaya fall in love and decide to get married.",
  "faithful; \\emph{fall in love} $\\to$ \\dev{प्यार में पड़ना} is correct.", "plain"),
 ("A1", "A hole is shown in the mouth.",
  "the translation is sound; the annotators simply split.", "std"),
 ("A2", "Blown through the opening at the end of the neck.",
  "\\emph{blown} mistranslated as \\dev{बहता है} (`flows'); the post-edit rewrites it.", "ter"),
 ("A3", "The terracotta human head with a pointed headdress.",
  "\\emph{headdress} $\\to$ \\dev{शीर्ष} (`top'); \\emph{terracotta} left untranslated.", "bad"),
 ("A4", "Plus we avoided a lot of confusion and wrote a cleaner code.",
  "below par for en-hi on the holistic score, yet the post-editor changed little.", "a4"),
]


def esc(s: str) -> str:
    return s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")


def main() -> int:
    d = load_challenge()
    d = d[d.language_pair == "en-hi"]
    pair_da30 = None  # printed in the caption so the A4 row is legible

    rows = []
    for head, src, gloss, sig in CHOSEN:
        r = d[d.source == src]
        if r.empty:
            print(f"REFUSING: exemplar not found in the challenge test: {src!r}")
            return 1
        r = r.iloc[0]
        iast = sanscript.transliterate(r["mt"], sanscript.DEVANAGARI, sanscript.IAST)
        da = f"{r['da_mean']:.0f}" if pd.notna(r["da_mean"]) else "--"
        try:
            raw = r["da_scores"]
            ann = [int(round(float(v))) for v in
                   (ast.literal_eval(raw) if isinstance(raw, str) else list(raw))]
        except Exception:
            ann = None
        if sig == "std":
            signal = f"da\\_std {r['da_std']:.0f}; scores {ann}"
        elif sig == "ter":
            signal = f"TER {r['human_ter']:.2f}, the pair's top quartile"
        elif sig == "bad":
            signal = f"\\textsc{{bad}}-tag density {r['bad_density']:.2f}"
        elif sig == "a4":
            signal = (f"DA {da} against a pair mean of $81.2$, TER {r['human_ter']:.2f} "
                      f"against $0.514$")
        else:
            signal = f"DA {da}, da\\_std {r['da_std']:.0f}"
        on = [a for a in AXES if bool(r[a])]
        rows.append((head, (f"\\textbf{{EN}} {esc(src)} \\newline "
                            f"\\textbf{{HI}} \\dev{{{r['mt']}}} \\newline "
                            f"\\textit{{{esc(iast)}}} \\newline "
                            f"\\footnotesize {gloss}"), da, signal,
                     ", ".join(f"\\texttt{{{a}}}" for a in on) or "---"))

    lines = [
     "% GENERATED by analysis/make_axis_examples_table.py — do not hand-edit.",
     "\\begin{table*}[t]\\centering\\small",
     "\\renewcommand{\\arraystretch}{1.15}",
     "\\begin{tabularx}{\\textwidth}{@{}l X r p{0.24\\textwidth} l@{}}",
     "\\toprule",
     "Axis & Example (English source; Hindi MT; IAST; note) & DA & Signal that places it "
     "& All axes \\\\",
     "\\midrule",
    ]
    for head, cell, da, signal, on in rows:
        lines.append(f"\\texttt{{{head}}} & {cell} & {da} & {signal} & {on} \\\\\n\\addlinespace")
    lines += [
     "\\bottomrule",
     "\\end{tabularx}",
     "\\caption{Verified en-hi segments from the \\texttt{challenge} config, one on each difficulty "
     "axis and one on none, with the signal that places each. \\texttt{da\\_std} is the standard "
     "deviation of the annotator scores, TER is MT$\\to$post-edit token TER, and "
     "\\textsc{bad}-tag density the fraction of word-level \\textsc{bad} tags. The last column "
     "lists every axis the segment carries, because the axes overlap: the \\texttt{A2} exemplar is "
     "also error-dense and the \\texttt{A4} one also carries \\texttt{A3}. Thresholds are taken "
     "within pair, so \\texttt{A4}'s direct assessment of $78$ is in the bottom $30\\%$ of en-hi, "
     "whose mean is $81.2$, while its TER of $0.29$ is well under the pair's $0.514$: the score "
     "says below par, the edit record says little needed doing.}",
     "\\label{tab:axis-examples}",
     "\\end{table*}",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
