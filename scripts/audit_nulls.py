#!/usr/bin/env python3
"""audit_nulls.py — null census for every column of every released config.

Produces, per config: rows, and for each column the null count / percentage. For `full` it also
breaks the key label columns down per language pair, because most nulls in this benchmark are
*structural* (a pair never had that annotation) rather than lost data — and the per-pair view is
what distinguishes the two.

Output: results/analysis/null_audit.md (+ stdout).
"""
from __future__ import annotations
import sys
from pathlib import Path
import pandas as pd
from huggingface_hub import hf_hub_download, HfApi

REPO = "surrey-nlp/IndicQE-APE"
SPLITS = ("train", "validation", "test")
CONFIGS = ["full", "all", "tasks/qe-da", "tasks/ape", "tasks/word-qe",
           "tasks/explainable-qe", "tasks/mqm", "challenge"]
PAIRS = ["en-hi", "en-mr", "en-gu", "en-ta", "en-te", "en-ml", "et-en", "ne-en", "si-en"]
OUT = Path("results/analysis/null_audit.md")


def empty(s: pd.Series) -> pd.Series:
    """A value counts as absent if it is NA, an empty/whitespace string, or an empty list."""
    if s.dtype == object:
        def _e(v):
            if v is None: return True
            if isinstance(v, float) and pd.isna(v): return True
            if isinstance(v, str): return v.strip() == ""
            if isinstance(v, (list, tuple)): return len(v) == 0
            try:
                if hasattr(v, "__len__"): return len(v) == 0
            except Exception:
                pass
            return False
        return s.map(_e)
    return s.isna()


def load(cfg):
    fr = []
    files = set(HfApi().list_repo_files(REPO, repo_type="dataset"))
    for sp in SPLITS:
        p = f"data/{cfg}/{sp}.parquet"
        if p not in files:
            continue
        d = pd.read_parquet(hf_hub_download(REPO, p, repo_type="dataset"))
        d["_split"] = sp
        fr.append(d)
    return pd.concat(fr, ignore_index=True) if fr else pd.DataFrame()


def main():
    lines = ["# Null census — surrey-nlp/IndicQE-APE\n",
             "Absent = null, empty string, or empty list. Generated by `scripts/audit_nulls.py`.\n"]
    full = None
    for cfg in CONFIGS:
        d = load(cfg)
        if d.empty:
            print(f"{cfg}: NOT FOUND"); continue
        if cfg == "full":
            full = d
        n = len(d)
        print(f"\n===== {cfg}: {n} rows, {len(d.columns)-1} columns =====")
        lines.append(f"\n## `{cfg}` — {n:,} rows\n\n| column | non-null | null | null % |\n|---|--:|--:|--:|\n")
        rows = []
        for c in d.columns:
            if c == "_split":
                continue
            k = int(empty(d[c]).sum())
            rows.append((c, n - k, k, 100.0 * k / n))
        for c, nn, k, pct in sorted(rows, key=lambda r: -r[3]):
            lines.append(f"| `{c}` | {nn:,} | {k:,} | {pct:.1f}% |\n")
            if pct > 0:
                print(f"  {c:<28} null {k:>7,} ({pct:5.1f}%)")

    # per-pair breakdown of the label columns on the master table
    if full is not None:
        key_cols = [c for c in ["da_mean", "da_scores", "da_z_mean", "post_edit", "wtag",
                                "wtag_derived", "mt_tokens", "wtag_gaps", "source_tags",
                                "source_tokens", "mqm_score", "mqm_spans", "domain",
                                "synthetic_description", "error_categories", "human_ter",
                                "reference", "tqr", "route", "n_annotators", "da_conflict"]
                    if c in full.columns]
        lines.append("\n## `full` — non-null count per language pair\n\n")
        lines.append("| column | " + " | ".join(PAIRS) + " |\n|---" * (len(PAIRS) + 1) + "|\n")
        print("\n===== full: non-null per pair =====")
        print(f"{'column':<26}" + "".join(f"{p:>9}" for p in PAIRS))
        for c in key_cols:
            cells = []
            for p in PAIRS:
                g = full[full.language_pair == p]
                cells.append(int((~empty(g[c])).sum()))
            lines.append(f"| `{c}` | " + " | ".join(f"{v:,}" for v in cells) + " |\n")
            print(f"{c:<26}" + "".join(f"{v:>9,}" for v in cells))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(lines))
    print(f"\nwritten {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
